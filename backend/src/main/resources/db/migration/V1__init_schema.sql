-- ============================================================
-- Appointment Booking System - initial schema (PostgreSQL 13+)
-- Also runs on H2 in PostgreSQL compatibility mode (dev/tests).
-- ============================================================

CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(100) NOT NULL,
    email                 VARCHAR(150) NOT NULL,
    phone                 VARCHAR(20),
    password_hash         VARCHAR(255) NOT NULL,
    role                  VARCHAR(20)  NOT NULL,
    is_verified           BOOLEAN      NOT NULL DEFAULT FALSE,
    is_phone_verified     BOOLEAN      NOT NULL DEFAULT FALSE,
    photo_url             VARCHAR(500),
    google_id             VARCHAR(150),
    notif_email           BOOLEAN      NOT NULL DEFAULT TRUE,
    notif_sms             BOOLEAN      NOT NULL DEFAULT TRUE,
    notif_push            BOOLEAN      NOT NULL DEFAULT TRUE,
    language              VARCHAR(10),
    timezone              VARCHAR(60),
    is_active             BOOLEAN      NOT NULL DEFAULT TRUE,
    is_deleted            BOOLEAN      NOT NULL DEFAULT FALSE,
    token_version         INTEGER      NOT NULL DEFAULT 0,
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMP,
    last_login_at         TIMESTAMP,
    created_at            TIMESTAMP,
    updated_at            TIMESTAMP,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT uk_users_google UNIQUE (google_id)
);
CREATE INDEX idx_users_role ON users (role);
CREATE INDEX idx_users_phone ON users (phone);

CREATE TABLE verification_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose     VARCHAR(20) NOT NULL,
    code_hash   VARCHAR(100) NOT NULL,
    expires_at  TIMESTAMP   NOT NULL,
    attempts    INTEGER     NOT NULL DEFAULT 0,
    consumed_at TIMESTAMP,
    created_at  TIMESTAMP
);
CREATE INDEX idx_vcode_user_purpose ON verification_codes (user_id, purpose);

CREATE TABLE password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(100) NOT NULL,
    expires_at TIMESTAMP    NOT NULL,
    used_at    TIMESTAMP,
    created_at TIMESTAMP,
    CONSTRAINT uk_reset_token_hash UNIQUE (token_hash)
);

CREATE TABLE addresses (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label        VARCHAR(60),
    address_line VARCHAR(255) NOT NULL,
    city         VARCHAR(100),
    state        VARCHAR(100),
    country      VARCHAR(60),
    zip          VARCHAR(20),
    latitude     DOUBLE PRECISION,
    longitude    DOUBLE PRECISION,
    is_default   BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    icon        VARCHAR(100),
    slug        VARCHAR(120) NOT NULL,
    description VARCHAR(255),
    CONSTRAINT uk_categories_name UNIQUE (name),
    CONSTRAINT uk_categories_slug UNIQUE (slug)
);

CREATE TABLE providers (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                    BIGINT       NOT NULL REFERENCES users (id),
    business_name              VARCHAR(120) NOT NULL,
    description                TEXT,
    specialty                  VARCHAR(120),
    logo_url                   VARCHAR(500),
    cover_url                  VARCHAR(500),
    category_id                BIGINT REFERENCES categories (id),
    city                       VARCHAR(100),
    state                      VARCHAR(100),
    country                    VARCHAR(100),
    address                    VARCHAR(255),
    latitude                   DOUBLE PRECISION,
    longitude                  DOUBLE PRECISION,
    phone                      VARCHAR(20),
    website                    VARCHAR(200),
    timezone                   VARCHAR(60)  NOT NULL DEFAULT 'Asia/Kolkata',
    status                     VARCHAR(20)  NOT NULL,
    rating_avg                 DOUBLE PRECISION NOT NULL DEFAULT 0,
    review_count               INTEGER      NOT NULL DEFAULT 0,
    slot_interval_min          INTEGER      NOT NULL DEFAULT 0,
    max_bookings_per_day       INTEGER      NOT NULL DEFAULT 0,
    max_bookings_per_slot      INTEGER      NOT NULL DEFAULT 1,
    min_notice_min             INTEGER      NOT NULL DEFAULT 60,
    max_advance_booking_days   INTEGER      NOT NULL DEFAULT 30,
    auto_confirm               BOOLEAN      NOT NULL DEFAULT TRUE,
    cancellation_cutoff_hours  INTEGER      NOT NULL DEFAULT 24,
    late_cancel_refund_percent INTEGER      NOT NULL DEFAULT 50,
    reschedule_cutoff_hours    INTEGER      NOT NULL DEFAULT 12,
    max_reschedules            INTEGER      NOT NULL DEFAULT 2,
    cancellation_policy        VARCHAR(500),
    admin_note                 VARCHAR(500),
    created_at                 TIMESTAMP,
    updated_at                 TIMESTAMP,
    CONSTRAINT uk_providers_user UNIQUE (user_id)
);
CREATE INDEX idx_providers_city ON providers (city);
CREATE INDEX idx_providers_status ON providers (status);

CREATE TABLE provider_branches (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT       NOT NULL REFERENCES providers (id) ON DELETE CASCADE,
    name        VARCHAR(120) NOT NULL,
    address     VARCHAR(255),
    city        VARCHAR(100),
    state       VARCHAR(100),
    country     VARCHAR(100),
    latitude    DOUBLE PRECISION,
    longitude   DOUBLE PRECISION,
    phone       VARCHAR(20),
    is_main     BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE services (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id              BIGINT       NOT NULL REFERENCES providers (id),
    name                     VARCHAR(120) NOT NULL,
    description              TEXT,
    duration_min             INTEGER      NOT NULL,
    buffer_min               INTEGER      NOT NULL DEFAULT 0,
    price                    DOUBLE PRECISION NOT NULL,
    deposit_percent          INTEGER      NOT NULL DEFAULT 0,
    mode                     VARCHAR(20)  NOT NULL DEFAULT 'IN_PERSON',
    category_id              BIGINT REFERENCES categories (id),
    image_url                VARCHAR(500),
    max_advance_booking_days INTEGER      NOT NULL DEFAULT 0,
    is_active                BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at               TIMESTAMP
);
CREATE INDEX idx_services_provider ON services (provider_id);
CREATE INDEX idx_services_category ON services (category_id);

CREATE TABLE staff (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT       NOT NULL REFERENCES providers (id),
    user_id     BIGINT REFERENCES users (id),
    name        VARCHAR(120) NOT NULL,
    designation VARCHAR(120),
    photo_url   VARCHAR(500),
    bio         TEXT,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_staff_user UNIQUE (user_id)
);
CREATE INDEX idx_staff_provider ON staff (provider_id);

CREATE TABLE staff_services (
    service_id BIGINT NOT NULL REFERENCES services (id) ON DELETE CASCADE,
    staff_id   BIGINT NOT NULL REFERENCES staff (id) ON DELETE CASCADE,
    PRIMARY KEY (service_id, staff_id)
);

CREATE TABLE availability (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT  NOT NULL REFERENCES providers (id) ON DELETE CASCADE,
    staff_id    BIGINT REFERENCES staff (id) ON DELETE CASCADE,
    day_of_week INTEGER NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time  TIME    NOT NULL,
    end_time    TIME    NOT NULL,
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (start_time < end_time)
);
CREATE INDEX idx_avail_provider ON availability (provider_id);

CREATE TABLE blocked_dates (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id  BIGINT  NOT NULL REFERENCES providers (id) ON DELETE CASCADE,
    staff_id     BIGINT REFERENCES staff (id) ON DELETE CASCADE,
    date         DATE    NOT NULL,
    start_time   TIME,
    end_time     TIME,
    is_available BOOLEAN NOT NULL DEFAULT FALSE,
    reason       VARCHAR(255),
    CONSTRAINT uk_blocked_provider_staff_date UNIQUE (provider_id, staff_id, date)
);

CREATE TABLE slot_holds (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_token  VARCHAR(64) NOT NULL,
    provider_id BIGINT      NOT NULL,
    service_id  BIGINT      NOT NULL,
    staff_id    BIGINT,
    user_id     BIGINT      NOT NULL,
    date        DATE        NOT NULL,
    start_time  TIME        NOT NULL,
    start_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_slot_hold_token UNIQUE (hold_token)
);
CREATE INDEX idx_hold_provider_date ON slot_holds (provider_id, date);
CREATE INDEX idx_hold_expires ON slot_holds (expires_at);

CREATE TABLE coupons (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(40) NOT NULL,
    discount_type  VARCHAR(20) NOT NULL,
    discount_value DOUBLE PRECISION NOT NULL,
    min_order      DOUBLE PRECISION,
    max_discount   DOUBLE PRECISION,
    valid_from     DATE,
    valid_to       DATE,
    usage_limit    INTEGER     NOT NULL DEFAULT 0,
    used_count     INTEGER     NOT NULL DEFAULT 0,
    per_user_limit INTEGER     NOT NULL DEFAULT 0,
    is_active      BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMP,
    CONSTRAINT uk_coupons_code UNIQUE (code)
);

CREATE TABLE appointments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_ref       VARCHAR(40)  NOT NULL,
    customer_id       BIGINT       NOT NULL REFERENCES users (id),
    provider_id       BIGINT       NOT NULL REFERENCES providers (id),
    service_id        BIGINT       NOT NULL REFERENCES services (id),
    staff_id          BIGINT REFERENCES staff (id),
    date              DATE         NOT NULL,
    start_time        TIME         NOT NULL,
    end_time          TIME         NOT NULL,
    start_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    busy_until        TIMESTAMP WITH TIME ZONE NOT NULL,
    timezone          VARCHAR(60)  NOT NULL,
    slot_key          VARCHAR(120),
    status            VARCHAR(20)  NOT NULL,
    mode              VARCHAR(20)  NOT NULL DEFAULT 'IN_PERSON',
    meeting_link      VARCHAR(300),
    notes             TEXT,
    provider_notes    TEXT,
    amount            DOUBLE PRECISION NOT NULL,
    discount          DOUBLE PRECISION NOT NULL DEFAULT 0,
    final_amount      DOUBLE PRECISION NOT NULL,
    coupon_code       VARCHAR(40),
    payment_status    VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    cancel_reason     VARCHAR(500),
    cancelled_by      VARCHAR(20),
    cancelled_at      TIMESTAMP WITH TIME ZONE,
    reschedule_count  INTEGER      NOT NULL DEFAULT 0,
    reminder_24h_sent BOOLEAN      NOT NULL DEFAULT FALSE,
    reminder_1h_sent  BOOLEAN      NOT NULL DEFAULT FALSE,
    payment_due_at    TIMESTAMP WITH TIME ZONE,
    created_at        TIMESTAMP,
    updated_at        TIMESTAMP,
    CONSTRAINT uk_appt_booking_ref UNIQUE (booking_ref),
    -- Only occupied slots carry a key; a second active booking of the same
    -- resource/start/seat violates this constraint (FR-22, NFR-7).
    CONSTRAINT uk_appt_slot_key UNIQUE (slot_key),
    CHECK (end_at > start_at)
);
CREATE INDEX idx_appt_customer ON appointments (customer_id);
CREATE INDEX idx_appt_provider_date ON appointments (provider_id, date);
CREATE INDEX idx_appt_status ON appointments (status);
CREATE INDEX idx_appt_start_at ON appointments (start_at);

CREATE TABLE payments (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT      NOT NULL REFERENCES appointments (id),
    amount         DOUBLE PRECISION NOT NULL,
    balance_due    DOUBLE PRECISION NOT NULL DEFAULT 0,
    currency       VARCHAR(3)  NOT NULL DEFAULT 'INR',
    method         VARCHAR(30) NOT NULL,
    payment_option VARCHAR(20) NOT NULL DEFAULT 'FULL',
    status         VARCHAR(20) NOT NULL,
    order_id       VARCHAR(100),
    transaction_id VARCHAR(100),
    refund_id      VARCHAR(100),
    refund_amount  DOUBLE PRECISION NOT NULL DEFAULT 0,
    invoice_number VARCHAR(40),
    paid_at        TIMESTAMP,
    refunded_at    TIMESTAMP,
    created_at     TIMESTAMP,
    CONSTRAINT uk_payments_appointment UNIQUE (appointment_id),
    CONSTRAINT uk_payments_order UNIQUE (order_id),
    CONSTRAINT uk_payments_txn UNIQUE (transaction_id),
    CONSTRAINT uk_payments_invoice UNIQUE (invoice_number)
);

CREATE TABLE reviews (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id  BIGINT      NOT NULL REFERENCES appointments (id),
    customer_id     BIGINT      NOT NULL REFERENCES users (id),
    provider_id     BIGINT      NOT NULL REFERENCES providers (id),
    rating          INTEGER     NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment         TEXT,
    status          VARCHAR(20) NOT NULL,
    moderation_note VARCHAR(500),
    moderated_at    TIMESTAMP,
    reply           TEXT,
    reply_at        TIMESTAMP,
    is_flagged      BOOLEAN     NOT NULL DEFAULT FALSE,
    flag_reason     VARCHAR(255),
    created_at      TIMESTAMP,
    CONSTRAINT uk_reviews_appointment UNIQUE (appointment_id)
);
CREATE INDEX idx_review_provider_status ON reviews (provider_id, status);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title      VARCHAR(150) NOT NULL,
    message    TEXT,
    type       VARCHAR(20)  NOT NULL,
    link       VARCHAR(200),
    is_read    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP
);
CREATE INDEX idx_notif_user_read ON notifications (user_id, is_read);

CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT,
    actor_email VARCHAR(150),
    actor_role  VARCHAR(20),
    action      VARCHAR(60) NOT NULL,
    entity_type VARCHAR(40),
    entity_id   BIGINT,
    details     TEXT,
    ip_address  VARCHAR(64),
    created_at  TIMESTAMP
);
CREATE INDEX idx_audit_created ON audit_logs (created_at);
CREATE INDEX idx_audit_actor ON audit_logs (actor_id);
CREATE INDEX idx_audit_entity ON audit_logs (entity_type, entity_id);
